-- NWG Coaches Hub — Permissions retcon P5: verification
--
-- Companion to supabase/migrations/0028_drop_legacy_role.sql. Written, not
-- executed.
--
-- ---------------------------------------------------------------------------
-- PASTE ORDER
-- ---------------------------------------------------------------------------
--
--   Paste A  -> run BEFORE 0028 (it reads profiles.role, so it fails after)
--   apply    supabase/migrations/0028_drop_legacy_role.sql
--   Paste B  -> run AFTER 0028
--
-- Paste each one into the Supabase SQL Editor on its own, as the editor's
-- default role (postgres). Each returns one result set:
--
--   check_name | expected | actual | pass
--
-- A good run shows pass = true on every check row. Paste A's rows whose
-- check_name starts with "info" have pass = null and are there to be read and
-- kept as the record of the role column before it goes. When a check fails,
-- its actual column names what was wrong.
--
-- Do not apply 0028 if Paste A has a failing row: 0028's guard repeats checks
-- A1–A5 and would abort anyway.
--
-- A4 (and 0028's guard 1e) match the word "role" anywhere in a public function
-- body, including comments. If A4 fails only because of a comment, report it;
-- do not loosen the pattern or edit the function to get past it.
--
-- What each check means:
--
--   Paste A
--     A1   objects Postgres records as depending on is_admin()/can_edit_rota()
--     A2   policies calling either function
--     A3   function bodies calling either function
--     A4   function bodies mentioning role, other than is_admin() and the guard
--          trigger function (both replaced or dropped by 0028)
--     A5   dependents of profiles.role: none that 0028 doesn't handle, and
--          exactly the 3 it does (default, check constraint, trigger)
--     A6   the role check constraint (name generated by Postgres from 0001)
--     A7   the role default is still 'coach'
--     A8   is_admin() and can_edit_rota() both exist (0028 drops them without
--          IF EXISTS)
--     A9   the guard trigger exists, is enabled, and its WHEN clause still
--          mentions role: the dependency 0028 must remove first
--     A10  66 policies call the capability helpers (baseline for B6)
--     A11  no profile has a null job_title, and the column is NOT NULL
--     A12  the public schema holds exactly the 28 tables the migrations
--          create, and nothing else (0028 revokes by table name)
--     info anon's current table and function privileges, the schema's
--          default privileges, and a role x job_title x active snapshot
--
--   Paste B
--     B1   profiles.role is gone
--     B2   is_admin() and can_edit_rota() are gone
--     B3   no policy or function body still calls either
--     B4   the guard trigger is the only user trigger on profiles, enabled,
--          BEFORE UPDATE FOR EACH ROW, WHEN on job_title/site/active, no role
--     B5   the guard trigger function: SECURITY INVOKER, search_path = '',
--          no role in its body, not executable by anon
--     B6   the 66 capability policies are still present
--     B7   anon holds no privilege on the 26 revoked tables, or on any other
--          public table, view or sequence
--     B8   authenticated still holds SELECT/INSERT/UPDATE/DELETE on all 28
--          tables (the revokes touched only anon and PUBLIC)
--     B9   anon can execute no public function. Deliberately allowed:
--          rls_auto_enable (Supabase-managed, not created by our migrations).
--     B10  postgres's default privileges in public grant anon nothing


-- ===========================================================================
-- PASTE A — before 0028
-- ===========================================================================

with
pol as (
  select tablename::text as tablename,
         policyname::text as policyname,
         coalesce(qual, '') || ' ' || coalesce(with_check, '') as body
  from pg_policies
  where schemaname = 'public'
),
fn as (
  select p.oid, p.proname::text as proname, p.prosrc
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace
    and not exists (
      select 1 from pg_depend d
      where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e'
    )
),
legacy_fn as (
  select oid, proname from fn where proname in ('is_admin', 'can_edit_rota')
),
legacy_deps as (
  select pg_describe_object(d.classid, d.objid, d.objsubid) as obj
  from pg_depend d
  join legacy_fn f on d.refobjid = f.oid
  where d.refclassid = 'pg_proc'::regclass
),
role_att as (
  select attnum from pg_attribute
  where attrelid = 'public.profiles'::regclass and attname = 'role' and not attisdropped
),
role_check as (
  select c.oid, c.conname::text as conname
  from pg_constraint c
  join role_att a on c.conkey = array[a.attnum]
  where c.conrelid = 'public.profiles'::regclass and c.contype = 'c'
),
guard_trg as (
  select t.oid, t.tgenabled, pg_get_triggerdef(t.oid) as def
  from pg_trigger t
  where t.tgrelid = 'public.profiles'::regclass
    and t.tgname = 'profiles_guard_privileged_columns'
),
role_deps as (
  select distinct
         pg_describe_object(d.classid, d.objid, d.objsubid) as obj,
         (d.classid = 'pg_attrdef'::regclass
          or (d.classid = 'pg_constraint'::regclass and d.objid in (select oid from role_check))
          or (d.classid = 'pg_trigger'::regclass and d.objid in (select oid from guard_trg))) as handled
  from pg_depend d
  join role_att a on d.refobjsubid = a.attnum
  where d.refclassid = 'pg_class'::regclass
    and d.refobjid = 'public.profiles'::regclass
),
known_tables (relname) as (
  values
    ('profiles'), ('rota_sites'), ('rota_categories'), ('rota_class_catalogue'),
    ('rota_coaches'), ('rota_standard_roster'), ('rota_standard_classes'),
    ('rota_weekly_rotas'), ('rota_weekly_roster'), ('rota_weekly_classes'),
    ('rota_restructures'), ('rota_restructure_roster'), ('rota_restructure_classes'),
    ('club_role_categories'), ('club_roles'), ('club_role_assignments'),
    ('heroes'), ('hero_hours'), ('club_updates'),
    ('club_meetings'), ('club_meeting_attendees'), ('club_meeting_cycle_weeks'),
    ('mantras'), ('cycle_weeks'), ('programme_gymnastics_weeks'),
    ('programme_preschool_weeks'), ('policies'), ('whats_new')
),
rel as (
  select c.oid, c.relname::text as relname, c.relkind
  from pg_class c
  where c.relnamespace = 'public'::regnamespace
    and c.relkind in ('r', 'p', 'v', 'm', 'f', 'S')
),
checks as (
  select 10 as ord, 0::bigint as sub,
         'A1 catalogued dependents of is_admin()/can_edit_rota()' as check_name,
         '0' as expected,
         count(*)::text || coalesce(': ' || string_agg(obj, ', ' order by obj), '') as actual,
         count(*) = 0 as pass
  from legacy_deps
  union all
  select 20, 0, 'A2 policies calling is_admin()/can_edit_rota()', '0',
         count(*)::text || coalesce(': ' || string_agg(tablename || '.' || policyname, ', ' order by tablename, policyname), ''),
         count(*) = 0
  from pol where body ~ '(is_admin|can_edit_rota)\s*\('
  union all
  select 30, 0, 'A3 functions calling is_admin()/can_edit_rota()', '0',
         count(*)::text || coalesce(': ' || string_agg(proname, ', ' order by proname), ''),
         count(*) = 0
  from fn
  where prosrc ~ '\m(is_admin|can_edit_rota)\s*\('
    and proname not in ('is_admin', 'can_edit_rota')
  union all
  select 40, 0, 'A4 functions mentioning role (excl. is_admin, guard trigger fn)', '0',
         count(*)::text || coalesce(': ' || string_agg(proname, ', ' order by proname), ''),
         count(*) = 0
  from fn
  where prosrc ~ '\mrole\M'
    and proname not in ('is_admin', 'profiles_guard_privileged_columns')
  union all
  select 50, 0, 'A5 dependents of profiles.role that 0028 does not handle', '0',
         count(*)::text || coalesce(': ' || string_agg(obj, ', ' order by obj), ''),
         count(*) = 0
  from role_deps where not handled
  union all
  select 51, 0, 'A5 dependents of profiles.role 0028 handles (default, check, trigger)', '3',
         count(*)::text || coalesce(': ' || string_agg(obj, ', ' order by obj), ''),
         count(*) = 3
  from role_deps where handled
  union all
  select 60, 0, 'A6 profiles.role check constraint', '1',
         count(*)::text || coalesce(': ' || string_agg(conname, ', '), ''),
         count(*) = 1
  from role_check
  union all
  select 70, 0, 'A7 profiles.role default', '''coach''::text',
         coalesce(max(column_default), '(no default)'),
         coalesce(max(column_default), '') = '''coach''::text'
  from information_schema.columns
  where table_schema = 'public' and table_name = 'profiles' and column_name = 'role'
  union all
  select 80, 0, 'A8 is_admin() present', '1', count(*)::text, count(*) = 1
  from legacy_fn where proname = 'is_admin'
  union all
  select 81, 0, 'A8 can_edit_rota() present', '1', count(*)::text, count(*) = 1
  from legacy_fn where proname = 'can_edit_rota'
  union all
  select 90, 0, 'A9 guard trigger present, enabled, WHEN still mentions role', '1',
         count(*)::text || coalesce(': ' || string_agg(def, ' | '), ''),
         count(*) = 1 and coalesce(bool_and(tgenabled = 'O' and def ~ '\mrole\M'), false)
  from guard_trg
  union all
  select 100, 0, 'A10 policies calling has_capability()/has_site_capability()', '66',
         count(*)::text, count(*) = 66
  from pol where body ~ 'has_(site_)?capability\('
  union all
  select 110, 0, 'A11 profiles with null job_title', '0', count(*)::text, count(*) = 0
  from public.profiles where job_title is null
  union all
  select 111, 0, 'A11 profiles.job_title is NOT NULL', 'true', attnotnull::text, attnotnull
  from pg_attribute
  where attrelid = 'public.profiles'::regclass and attname = 'job_title'
  union all
  select 120, 0, 'A12 public tables/views/sequences unknown to the migrations', '0',
         count(*)::text || coalesce(': ' || string_agg(relname, ', ' order by relname), ''),
         count(*) = 0
  from rel where relname not in (select relname from known_tables)
  union all
  select 121, 0, 'A12 known tables present', '28', count(*)::text, count(*) = 28
  from rel join known_tables k using (relname)
  where rel.relkind in ('r', 'p')
  union all
  select 200, 0, 'info anon holds privileges on', null,
         count(*)::text || coalesce(': ' || string_agg(relname, ', ' order by relname), ''),
         null
  from rel
  where case when relkind = 'S'
             then has_sequence_privilege('anon', oid, 'USAGE,SELECT,UPDATE')
             else has_table_privilege('anon', oid, 'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
                  or has_any_column_privilege('anon', oid, 'SELECT,INSERT,UPDATE,REFERENCES')
        end
  union all
  select 210, 0, 'info anon can execute', null,
         count(*)::text || coalesce(': ' || string_agg(proname, ', ' order by proname), ''),
         null
  from fn where has_function_privilege('anon', oid, 'EXECUTE')
  union all
  select 220, 0, 'info default privileges in schema public', null,
         coalesce(string_agg(pg_get_userbyid(defaclrole) || ' ' || defaclobjtype::text || ' ' || defaclacl::text,
                             ' | ' order by defaclrole, defaclobjtype), '(none)'),
         null
  from pg_default_acl where defaclnamespace = 'public'::regnamespace
  union all
  select 300, row_number() over (order by role, job_title, active desc),
         'info ' || role || ' / ' || job_title || ' / ' || case when active then 'active' else 'inactive' end,
         null, n::text, null
  from (
    select role, job_title, active, count(*) as n
    from public.profiles
    group by role, job_title, active
  ) s
)
select check_name, expected, actual, pass
from checks
order by ord, sub;



with
pol as (
  select tablename::text as tablename,
         policyname::text as policyname,
         coalesce(qual, '') || ' ' || coalesce(with_check, '') as body
  from pg_policies
  where schemaname = 'public'
),
fn as (
  select p.oid, p.proname::text as proname, p.prosrc
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace
    and not exists (
      select 1 from pg_depend d
      where d.classid = 'pg_proc'::regclass and d.objid = p.oid and d.deptype = 'e'
    )
),
guard_trg as (
  select t.tgname::text as tgname, t.tgenabled, pg_get_triggerdef(t.oid) as def
  from pg_trigger t
  where t.tgrelid = 'public.profiles'::regclass and not t.tgisinternal
),
guard_fn as (
  select format('secdef=%s config=%s role_in_body=%s anon=%s',
                p.prosecdef,
                coalesce(array_to_string(p.proconfig, ','), '(none)'),
                p.prosrc ~ '\mrole\M',
                has_function_privilege('anon', p.oid, 'EXECUTE')) as actual
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace
    and p.proname = 'profiles_guard_privileged_columns'
),
revoked (relname) as (
  values
    ('profiles'), ('rota_sites'), ('rota_categories'), ('rota_class_catalogue'),
    ('rota_coaches'), ('rota_standard_roster'), ('rota_standard_classes'),
    ('rota_weekly_rotas'), ('rota_weekly_roster'), ('rota_weekly_classes'),
    ('rota_restructures'), ('rota_restructure_roster'), ('rota_restructure_classes'),
    ('club_role_categories'), ('club_roles'), ('club_role_assignments'),
    ('heroes'), ('hero_hours'), ('club_updates'),
    ('club_meetings'), ('club_meeting_attendees'), ('club_meeting_cycle_weeks'),
    ('mantras'), ('cycle_weeks'), ('programme_gymnastics_weeks'),
    ('programme_preschool_weeks')
),
app_tables (relname) as (
  select relname from revoked
  union all
  values ('policies'), ('whats_new')
),
rel as (
  select c.oid, c.relname::text as relname, c.relkind
  from pg_class c
  where c.relnamespace = 'public'::regnamespace
    and c.relkind in ('r', 'p', 'v', 'm', 'f', 'S')
),
anon_rel as (
  select relname from rel
  where case when relkind = 'S'
             then has_sequence_privilege('anon', oid, 'USAGE,SELECT,UPDATE')
             else has_table_privilege('anon', oid, 'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
                  or has_any_column_privilege('anon', oid, 'SELECT,INSERT,UPDATE,REFERENCES')
        end
),
checks as (
  select 10 as ord,
         'B1 profiles.role column' as check_name,
         '0' as expected,
         count(*)::text as actual,
         count(*) = 0 as pass
  from information_schema.columns
  where table_schema = 'public' and table_name = 'profiles' and column_name = 'role'
  union all
  select 20, 'B2 is_admin()', '0', count(*)::text, count(*) = 0
  from pg_proc where pronamespace = 'public'::regnamespace and proname = 'is_admin'
  union all
  select 21, 'B2 can_edit_rota()', '0', count(*)::text, count(*) = 0
  from pg_proc where pronamespace = 'public'::regnamespace and proname = 'can_edit_rota'
  union all
  select 30, 'B3 policies/functions still calling is_admin()/can_edit_rota()', '0',
         count(*)::text || coalesce(': ' || string_agg(src, ', ' order by src), ''),
         count(*) = 0
  from (
    select 'policy ' || tablename || '.' || policyname as src from pol
    where body ~ '(is_admin|can_edit_rota)\s*\('
    union all
    select 'function ' || proname from fn
    where prosrc ~ '\m(is_admin|can_edit_rota)\s*\('
  ) s
  union all
  select 40, 'B4 profiles triggers: guard only, enabled, WHEN on job_title/site/active, no role',
         '1 trigger, all conditions met',
         count(*)::text || ' trigger(s)' || coalesce(': ' || string_agg(tgname || ' enabled=' || tgenabled::text || ' ' || def, ' | '), ''),
         count(*) = 1 and coalesce(bool_and(
           tgname = 'profiles_guard_privileged_columns'
           and tgenabled = 'O'
           and def ~ 'BEFORE UPDATE .* FOR EACH ROW WHEN .*old\.job_title.*old\.site.*old\.active.* IS DISTINCT FROM'
           and def !~ '\mrole\M'
         ), false)
  from guard_trg
  union all
  select 50, 'B5 guard trigger function',
         'secdef=f config=search_path="" role_in_body=f anon=f',
         coalesce(max(actual), '(function missing)'),
         coalesce(max(actual), '') = 'secdef=f config=search_path="" role_in_body=f anon=f'
           and count(*) = 1
  from guard_fn
  union all
  select 60, 'B6 policies calling has_capability()/has_site_capability()', '66',
         count(*)::text, count(*) = 66
  from pol where body ~ 'has_(site_)?capability\('
  union all
  select 70, 'B7 anon privileges on the 26 revoked tables', '0',
         count(*)::text || coalesce(': ' || string_agg(relname, ', ' order by relname), ''),
         count(*) = 0
  from anon_rel where relname in (select relname from revoked)
  union all
  select 71, 'B7 anon privileges on any public table/view/sequence', '0',
         count(*)::text || coalesce(': ' || string_agg(relname, ', ' order by relname), ''),
         count(*) = 0
  from anon_rel
  union all
  select 80, 'B8 app tables where authenticated lacks SELECT/INSERT/UPDATE/DELETE', '0',
         count(*)::text || coalesce(': ' || string_agg(a.relname, ', ' order by a.relname), ''),
         count(*) = 0
  from app_tables a
  left join rel r on r.relname = a.relname and r.relkind in ('r', 'p')
  where r.oid is null
     or not (has_table_privilege('authenticated', r.oid, 'SELECT')
             and has_table_privilege('authenticated', r.oid, 'INSERT')
             and has_table_privilege('authenticated', r.oid, 'UPDATE')
             and has_table_privilege('authenticated', r.oid, 'DELETE'))
  union all
  -- rls_auto_enable is created and managed by Supabase, not by any migration
  -- here, so its grants are Supabase's to set. It is allowed rather than
  -- revoked.
  select 90, 'B9 public functions anon can execute (allowed: rls_auto_enable)', '0',
         count(*)::text || coalesce(': ' || string_agg(proname, ', ' order by proname), ''),
         count(*) = 0
  from fn
  where has_function_privilege('anon', oid, 'EXECUTE')
    and proname not in ('rls_auto_enable')
  union all
  select 100, 'B10 postgres default privileges in public granting anon anything', '0',
         count(*)::text || coalesce(': ' || string_agg(d.defaclobjtype::text || ' ' || a.privilege_type, ', '), ''),
         count(*) = 0
  from pg_default_acl d
  cross join lateral aclexplode(d.defaclacl) a
  where d.defaclnamespace = 'public'::regnamespace
    and d.defaclrole = 'postgres'::regrole
    and a.grantee = 'anon'::regrole
)
select check_name, expected, actual, pass
from checks
order by ord;
